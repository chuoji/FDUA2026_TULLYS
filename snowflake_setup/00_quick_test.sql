SELECT "コード",
       "本社所在地",
       "業種分類",
       COUNT(*) AS YEARS
FROM FINANCIAL_DATA
GROUP BY "コード", "本社所在地", "業種分類"
ORDER BY "コード";

-- 年度別レコード数
SELECT YEAR,
       COUNT(*) AS COMPANIES
FROM FINANCIAL_DATA
GROUP BY YEAR
ORDER BY YEAR;

